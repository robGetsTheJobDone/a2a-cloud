@router.get("/status", response_model=ComplianceStatusOut)
async def get_status(
    slug: str,
    user: User = Depends(current_user),
    session: AsyncSession = Depends(get_session),
) -> ComplianceStatusOut:
    org, _ = await _member_org(slug, user, session, admin=True)
    policy = _policy_out(await _policy_row(org, session))

    receipt_count, oldest_receipt = (
        await session.execute(
            select(sa_func.count(), sa_func.min(AgentReceipt.created_at))
            .select_from(AgentReceipt)
            .join(Agent, Agent.id == AgentReceipt.agent_id)
            .where(Agent.organization_id == org.id)
        )
    ).one()
    member_ids = select(OrganizationMember.user_id).where(
        OrganizationMember.organization_id == org.id
    )
    grant_count = (
        await session.execute(
            select(sa_func.count()).select_from(GrantAudit).where(
                GrantAudit.user_id.in_(member_ids)
            )
        )
    ).scalar_one()
    admin_count = (
        await session.execute(
            select(sa_func.count()).select_from(OrganizationAuditLog).where(
                OrganizationAuditLog.organization_id == org.id
            )
        )
    ).scalar_one()

    agents_total = (
        await session.execute(
            select(sa_func.count()).select_from(Agent).where(
                Agent.organization_id == org.id
            )
        )
    ).scalar_one()
    agents_classified = (
        await session.execute(
            select(sa_func.count())
            .select_from(AgentComplianceProfile)
            .where(
                AgentComplianceProfile.organization_id == org.id,
                AgentComplianceProfile.risk_tier != "unclassified",
            )
        )
    ).scalar_one()
    agents_high_risk = (
        await session.execute(
            select(sa_func.count())
            .select_from(AgentComplianceProfile)
            .where(
                AgentComplianceProfile.organization_id == org.id,
                AgentComplianceProfile.risk_tier.in_(("high", "unacceptable")),
            )
        )
    ).scalar_one()

    now = datetime.now(timezone.utc)
    return ComplianceStatusOut(
        policy=policy,
        retention_ok=policy.retention_days >= policy.retention_floor_days,
        enforcement_date=EU_AI_ACT_ENFORCEMENT_DATE,
        days_until_enforcement=max(0, (EU_AI_ACT_ENFORCEMENT_DATE - now).days),
        record_counts={
            "skill_execution": int(receipt_count),
            "authorization": int(grant_count),
            "admin_action": int(admin_count),
        },
        oldest_record_at=oldest_receipt,
        agents_total=int(agents_total),
        agents_classified=int(agents_classified),
        agents_high_risk=int(agents_high_risk),
    )


