# Helpers


def _retention_floor(frameworks: list[str]) -> int:
    return EU_AI_ACT_MIN_RETENTION_DAYS if "eu_ai_act" in frameworks else 1


async def _policy_row(
    org: Organization, session: AsyncSession
) -> OrganizationCompliancePolicy | None:
    return (
        await session.execute(
            select(OrganizationCompliancePolicy).where(
                OrganizationCompliancePolicy.organization_id == org.id
            )
        )
    ).scalar_one_or_none()


def _policy_out(row: OrganizationCompliancePolicy | None) -> CompliancePolicyOut:
    frameworks = list(row.frameworks) if row is not None else ["eu_ai_act"]
    return CompliancePolicyOut(
        frameworks=frameworks,
        retention_days=row.retention_days if row is not None else DEFAULT_RETENTION_DAYS,
        retention_floor_days=_retention_floor(frameworks),
        legal_hold=row.legal_hold if row is not None else False,
        legal_hold_reason=row.legal_hold_reason if row is not None else None,
        updated_at=row.updated_at if row is not None else None,
        persisted=row is not None,
    )


def _receipt_record(row: AgentReceipt) -> DecisionRecordOut:
    payload = row.payload or {}
    return DecisionRecordOut(
        record_id=row.receipt_id,
        kind="skill_execution",
        recorded_at=row.created_at,
        occurred_at=row.started_at or row.created_at,
        agent_name=row.agent_name,
        actor=row.caller or "unknown",
        action=f"skill:{row.skill_name}",
        outcome=row.status,
        verifiable=True,
        details={
            "task_id": row.task_id,
            "agent_version": row.agent_version,
            "elapsed_ms": row.elapsed_ms,
            "eval_score": row.eval_score,
            "grant_ids": payload.get("grant_ids", []),
            "tool_calls": len(payload.get("tool_calls", []) or []),
            "handoffs": len(payload.get("handoffs", []) or []),
        },
    )


def _grant_record(row: GrantAudit) -> DecisionRecordOut:
    return DecisionRecordOut(
        record_id=row.grant_id,
        kind="authorization",
        recorded_at=row.created_at,
        occurred_at=row.created_at,
        agent_name=row.audience,
        actor=row.issuer,
        action=f"grant:{row.bucket}:{row.mode}",
        outcome=row.decision,
        verifiable=False,
        details={
            "decided_by": row.decided_by,
            "reason": row.reason,
            "parent_grant_id": row.parent_grant_id,
            "ttl_seconds": row.ttl_seconds,
            "allow_patterns": row.allow_patterns or [],
            "deny_patterns": row.deny_patterns or [],
        },
    )


def _admin_record(row: OrganizationAuditLog) -> DecisionRecordOut:
    return DecisionRecordOut(
        record_id=f"orgaudit-{row.id}",
        kind="admin_action",
        recorded_at=row.created_at,
        occurred_at=row.created_at,
        agent_name=None,
        actor=row.actor or "system",
        action=row.action,
        outcome="recorded",
        verifiable=False,
        details={
            "target_type": row.target_type,
            "target_id": row.target_id,
            "target_email": row.target_email,
            "data": row.data or {},
        },
    )


def _time_bounds(stmt, column, from_at: datetime | None, to_at: datetime | None):
    if from_at is not None:
        stmt = stmt.where(column >= from_at)
    if to_at is not None:
        stmt = stmt.where(column < to_at)
    return stmt


async def _query_receipts(
    org: Organization,
    session: AsyncSession,
    *,
    agent: str | None,
    outcome: str | None,
    from_at: datetime | None,
    to_at: datetime | None,
    limit: int,
) -> list[AgentReceipt]:
    stmt = (
        select(AgentReceipt)
        .join(Agent, Agent.id == AgentReceipt.agent_id)
        .where(Agent.organization_id == org.id)
        .order_by(AgentReceipt.created_at.desc())
        .limit(limit)
    )
    if agent:
        stmt = stmt.where(AgentReceipt.agent_name == agent)
    if outcome:
        stmt = stmt.where(AgentReceipt.status == outcome)
    stmt = _time_bounds(stmt, AgentReceipt.created_at, from_at, to_at)
    return list((await session.execute(stmt)).scalars().all())


async def _query_grants(
    org: Organization,
    session: AsyncSession,
    *,
    agent: str | None,
    outcome: str | None,
    from_at: datetime | None,
    to_at: datetime | None,
    limit: int,
) -> list[GrantAudit]:
    member_ids = select(OrganizationMember.user_id).where(
        OrganizationMember.organization_id == org.id
    )
    stmt = (
        select(GrantAudit)
        .where(GrantAudit.user_id.in_(member_ids))
        .order_by(GrantAudit.created_at.desc())
        .limit(limit)
    )
    if agent:
        stmt = stmt.where(GrantAudit.audience == agent)
    if outcome:
        stmt = stmt.where(GrantAudit.decision == outcome)
    stmt = _time_bounds(stmt, GrantAudit.created_at, from_at, to_at)
    return list((await session.execute(stmt)).scalars().all())


async def _query_admin_actions(
    org: Organization,
    session: AsyncSession,
    *,
    from_at: datetime | None,
    to_at: datetime | None,
    limit: int,
) -> list[OrganizationAuditLog]:
    stmt = (
        select(OrganizationAuditLog)
        .where(OrganizationAuditLog.organization_id == org.id)
        .order_by(OrganizationAuditLog.created_at.desc())
        .limit(limit)
    )
    stmt = _time_bounds(stmt, OrganizationAuditLog.created_at, from_at, to_at)
    return list((await session.execute(stmt)).scalars().all())


async def _collect_records(
    org: Organization,
    session: AsyncSession,
    *,
    kinds: list[str],
    agent: str | None = None,
    outcome: str | None = None,
    from_at: datetime | None = None,
    to_at: datetime | None = None,
    limit: int = 100,
) -> list[DecisionRecordOut]:
    records: list[DecisionRecordOut] = []
    if "skill_execution" in kinds:
        records += [
            _receipt_record(r)
            for r in await _query_receipts(
                org, session, agent=agent, outcome=outcome,
                from_at=from_at, to_at=to_at, limit=limit,
            )
        ]
    if "authorization" in kinds:
        records += [
            _grant_record(r)
            for r in await _query_grants(
                org, session, agent=agent, outcome=outcome,
                from_at=from_at, to_at=to_at, limit=limit,
            )
        ]
    if "admin_action" in kinds and not agent and not outcome:
        records += [
            _admin_record(r)
            for r in await _query_admin_actions(
                org, session, from_at=from_at, to_at=to_at, limit=limit,
            )
        ]
    records.sort(key=lambda r: r.recorded_at, reverse=True)
    return records[:limit]


