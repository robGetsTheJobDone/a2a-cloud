@router.post("/export")
async def export_evidence_pack(
    slug: str,
    body: EvidenceExportIn,
    user: User = Depends(current_user),
    session: AsyncSession = Depends(get_session),
) -> dict[str, Any]:
    org, _ = await _member_org(slug, user, session, admin=True)
    policy = _policy_out(await _policy_row(org, session))

    records = await _collect_records(
        org, session, kinds=list(body.kinds),
        from_at=body.from_at, to_at=body.to_at, limit=body.max_records,
    )

    verification = {"checked": 0, "valid": 0, "invalid": []}
    if body.verify_signatures and "skill_execution" in body.kinds:
        receipt_ids = [r.record_id for r in records if r.kind == "skill_execution"]
        if receipt_ids:
            rows = (
                await session.execute(
                    select(AgentReceipt.receipt_id, AgentReceipt.signed_token).where(
                        AgentReceipt.receipt_id.in_(receipt_ids)
                    )
                )
            ).all()
            for receipt_id, signed_token in rows:
                verification["checked"] += 1
                try:
                    verify_receipt(signed_token)
                    verification["valid"] += 1
                except ReceiptInvalid:
                    verification["invalid"].append(receipt_id)

    profile_rows = (
        await session.execute(
            select(Agent, AgentComplianceProfile)
            .outerjoin(
                AgentComplianceProfile,
                AgentComplianceProfile.agent_id == Agent.id,
            )
            .where(Agent.organization_id == org.id)
            .order_by(Agent.name)
        )
    ).all()
    inventory = [
        {
            "agent_name": agent.name,
            "agent_version": agent.version,
            "image": agent.image,
            "status": agent.status,
            "risk_tier": profile.risk_tier if profile else "unclassified",
            "intended_purpose": profile.intended_purpose if profile else "",
            "human_oversight": profile.human_oversight if profile else "",
        }
        for agent, profile in profile_rows
    ]

    _add_audit(
        session,
        org_id=org.id,
        action="compliance.evidence_exported",
        target_type="compliance_export",
        actor_user=user,
        data={
            "kinds": list(body.kinds),
            "record_count": len(records),
            "from_at": body.from_at.isoformat() if body.from_at else None,
            "to_at": body.to_at.isoformat() if body.to_at else None,
        },
    )
    await session.commit()

    now = datetime.now(timezone.utc)
    counts: dict[str, int] = {}
    for record in records:
        counts[record.kind] = counts.get(record.kind, 0) + 1
    return {
        "evidence_pack_version": "1",
        "generated_at": now.isoformat(),
        "generated_by": user.email,
        "organization": {"slug": org.slug, "name": org.name},
        "policy": policy.model_dump(mode="json"),
        "framework_controls": {
            f: FRAMEWORK_CONTROLS[f]
            for f in policy.frameworks
            if f in FRAMEWORK_CONTROLS
        },
        "agent_inventory": inventory,
        "record_counts": counts,
        "records": [r.model_dump(mode="json") for r in records],
        "signature_verification": verification,
        "truncated": len(records) >= body.max_records,
    }


