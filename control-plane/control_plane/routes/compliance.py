@router.get("/policy", response_model=CompliancePolicyOut)
async def get_policy(
    slug: str,
    user: User = Depends(current_user),
    session: AsyncSession = Depends(get_session),
) -> CompliancePolicyOut:
    org, _ = await _member_org(slug, user, session, admin=True)
    return _policy_out(await _policy_row(org, session))


@router.put("/policy", response_model=CompliancePolicyOut)
async def put_policy(
    slug: str,
    body: CompliancePolicyIn,
    user: User = Depends(current_user),
    session: AsyncSession = Depends(get_session),
) -> CompliancePolicyOut:
    org, _ = await _member_org(slug, user, session, admin=True)
    unknown = [f for f in body.frameworks if f not in KNOWN_FRAMEWORKS]
    if unknown:
        raise HTTPException(422, f"unknown frameworks: {unknown}")
    floor = _retention_floor(body.frameworks)
    if body.retention_days < floor:
        raise HTTPException(
            422,
            f"retention_days {body.retention_days} below the {floor}-day floor "
            "required while eu_ai_act is active (EU AI Act Art. 19)",
        )
    row = await _policy_row(org, session)
    if row is None:
        row = OrganizationCompliancePolicy(organization_id=org.id)
        session.add(row)
    row.frameworks = list(dict.fromkeys(body.frameworks))
    row.retention_days = body.retention_days
    row.legal_hold = body.legal_hold
    row.legal_hold_reason = body.legal_hold_reason if body.legal_hold else None
    row.updated_by_id = user.id
    _add_audit(
        session,
        org_id=org.id,
        action="compliance.policy_updated",
        target_type="compliance_policy",
        actor_user=user,
        data={
            "frameworks": row.frameworks,
            "retention_days": row.retention_days,
            "legal_hold": row.legal_hold,
        },
    )
    await session.commit()
    await session.refresh(row)
    return _policy_out(row)


