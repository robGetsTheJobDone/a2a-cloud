@router.post("/retention/enforce", response_model=RetentionEnforceOut)
async def enforce_retention(
    slug: str,
    user: User = Depends(current_user),
    session: AsyncSession = Depends(get_session),
) -> RetentionEnforceOut:
    org, member = await _member_org(slug, user, session, admin=True)
    if member.role != "owner":
        raise HTTPException(403, "organization owner required to purge records")
    row = await _policy_row(org, session)
    policy = _policy_out(row)
    if policy.legal_hold:
        raise HTTPException(
            409, "legal hold is active; retention purge is blocked"
        )
    # Re-derive the floor here: even if a stale/hand-edited policy row says
    # fewer days, the purge never reaches inside the Art. 19 window.
    effective_days = max(policy.retention_days, policy.retention_floor_days)
    cutoff = datetime.now(timezone.utc) - timedelta(days=effective_days)

    org_agent_ids = select(Agent.id).where(Agent.organization_id == org.id)
    receipts_deleted = (
        await session.execute(
            delete(AgentReceipt).where(
                AgentReceipt.agent_id.in_(org_agent_ids),
                AgentReceipt.created_at < cutoff,
            )
        )
    ).rowcount or 0
    admin_deleted = (
        await session.execute(
            delete(OrganizationAuditLog).where(
                OrganizationAuditLog.organization_id == org.id,
                OrganizationAuditLog.created_at < cutoff,
            )
        )
    ).rowcount or 0

    _add_audit(
        session,
        org_id=org.id,
        action="compliance.retention_enforced",
        target_type="compliance_policy",
        actor_user=user,
        data={
            "cutoff": cutoff.isoformat(),
            "receipts_deleted": receipts_deleted,
            "admin_actions_deleted": admin_deleted,
        },
    )
    await session.commit()
    return RetentionEnforceOut(
        cutoff=cutoff,
        receipts_deleted=receipts_deleted,
        admin_actions_deleted=admin_deleted,
        note=(
            "grant_audit rows are platform-scoped (a user may belong to "
            "several orgs) and are never purged by org-level retention"
        ),
    )
