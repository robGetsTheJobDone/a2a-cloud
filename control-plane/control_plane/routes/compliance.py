"""Org-facing AI-compliance surface (EU AI Act, NIST AI RMF, ISO/IEC 42001).

Decision records are *not* a new store — they are a normalized, queryable
view over the three audit surfaces the platform already writes on every
run: signed execution receipts (``agent_receipts``), the grant decision
chain (``grant_audit``), and the org admin trail
(``organization_audit_logs``). This route layer adds:

* a per-org retention policy with the EU AI Act Art. 19 floor (180 days)
  enforced at write *and* purge time, plus legal hold;
* a unified ``/decision-records`` query API (Art. 12 requires logs to be
  automatically recorded — receipts already do that — and usable);
* per-agent risk classification (Act risk tiers) + procurement metadata;
* a self-contained evidence-pack export with the framework control
  mapping inlined, for procurement / auditor handoff.

Every export and purge is itself written to the org audit log, so access
to compliance data is part of the compliance data.
"""
