@router.put("/agents/{agent_name}", response_model=AgentRiskProfileOut)
async def put_agent_profile(
    slug: str,
    agent_name: str,
    body: AgentRiskProfileIn,
    user: User = Depends(current_user),
    session: AsyncSession = Depends(get_session),
) -> AgentRiskProfileOut:
    org, _ = await _member_org(slug, user, session, admin=True)
    if body.risk_tier not in RISK_TIERS:
        raise HTTPException(422, f"risk_tier must be one of {RISK_TIERS}")
    agent = (
        await session.execute(
            select(Agent).where(
                Agent.name == agent_name, Agent.organization_id == org.id
            )
        )
    ).scalar_one_or_none()
    if agent is None:
        raise HTTPException(404, "agent not found in this organization")
    profile = (
        await session.execute(
            select(AgentComplianceProfile).where(
                AgentComplianceProfile.agent_id == agent.id
            )
        )
    ).scalar_one_or_none()
    if profile is None:
        profile = AgentComplianceProfile(agent_id=agent.id, organization_id=org.id)
        session.add(profile)
    profile.organization_id = org.id
    profile.risk_tier = body.risk_tier
    profile.intended_purpose = body.intended_purpose
    profile.human_oversight = body.human_oversight
    profile.notes = body.notes
    profile.updated_by_id = user.id
    _add_audit(
        session,
        org_id=org.id,
        action="compliance.agent_classified",
        target_type="agent",
        actor_user=user,
        target_id=agent.name,
        data={"risk_tier": body.risk_tier},
    )
    await session.commit()
    await session.refresh(profile)
    return AgentRiskProfileOut(
        agent_name=agent.name,
        agent_version=agent.version,
        risk_tier=profile.risk_tier,
        intended_purpose=profile.intended_purpose,
        human_oversight=profile.human_oversight,
        notes=profile.notes,
        updated_at=profile.updated_at,
    )


